"""Stable diagnostic vocabulary from the TASK-05 contract (v1.0.0), wire spelling verbatim.

Names and values are part of the contract: renaming or adding a member is a contract change
(minor version for additive changes, explicit revision otherwise) and needs approval.

This module deliberately maps nothing (no code -> classification, no pipeline stage):
those relations are not fixed by the contract and must not be invented here.
"""

from enum import StrEnum


class DiagnosticCode(StrEnum):
    # Source / endpoint
    SOURCE_IPV4_UNCONFIGURED = "SOURCE_IPV4_UNCONFIGURED"
    SOURCE_INTERFACE_DISABLED = "SOURCE_INTERFACE_DISABLED"
    SOURCE_LINK_DOWN = "SOURCE_LINK_DOWN"
    UNSUPPORTED_PING_ENDPOINT = "UNSUPPORTED_PING_ENDPOINT"  # normally ErrorEnvelope
    DUPLICATE_IP_ENDPOINT_CONFLICT = "DUPLICATE_IP_ENDPOINT_CONFLICT"
    MISSING_DEFAULT_GATEWAY = "MISSING_DEFAULT_GATEWAY"
    OFF_LINK_DEFAULT_GATEWAY = "OFF_LINK_DEFAULT_GATEWAY"
    SELF_REFERENCING_GATEWAY = "SELF_REFERENCING_GATEWAY"

    # Routing
    NO_MATCHING_ROUTE = "NO_MATCHING_ROUTE"
    NO_ELIGIBLE_ROUTE = "NO_ELIGIBLE_ROUTE"
    STATIC_NEXT_HOP_INELIGIBLE = "STATIC_NEXT_HOP_INELIGIBLE"
    NON_FORWARDING_GATEWAY = "NON_FORWARDING_GATEWAY"

    # ARP
    ARP_NO_RESPONSE = "ARP_NO_RESPONSE"
    ARP_AMBIGUOUS_RESPONSE = "ARP_AMBIGUOUS_RESPONSE"
    ARP_SAFETY_LIMITED = "ARP_SAFETY_LIMITED"
    ARP_RESOLUTION_DEADLINE = "ARP_RESOLUTION_DEADLINE"

    # ICMP / Ping
    TTL_EXPIRED = "TTL_EXPIRED"
    ICMP_ERROR_SUPPRESSED = "ICMP_ERROR_SUPPRESSED"
    ICMP_ERROR_DELIVERY_FAILED = "ICMP_ERROR_DELIVERY_FAILED"
    ECHO_REQUEST_DROPPED = "ECHO_REQUEST_DROPPED"
    ECHO_REPLY_DROPPED = "ECHO_REPLY_DROPPED"
    ECHO_REPLY_MISMATCH = "ECHO_REPLY_MISMATCH"
    ECHO_REPLY_DUPLICATE = "ECHO_REPLY_DUPLICATE"
    ECHO_REPLY_LATE = "ECHO_REPLY_LATE"
    ECHO_TIMEOUT = "ECHO_TIMEOUT"
    RETURN_PATH_FAILURE = "RETURN_PATH_FAILURE"

    # Execution limits
    FRAME_BRANCH_TRAVERSAL_LIMIT = "FRAME_BRANCH_TRAVERSAL_LIMIT"
    REQUEST_EVENT_BUDGET_EXHAUSTED = "REQUEST_EVENT_BUDGET_EXHAUSTED"
    TEST_EVENT_BUDGET_EXHAUSTED = "TEST_EVENT_BUDGET_EXHAUSTED"

    # L2 runtime
    MAC_FLAPPING_DETECTED = "MAC_FLAPPING_DETECTED"
    L2_LOOP_OBSERVED = "L2_LOOP_OBSERVED"

    # Observation
    OBSERVATION_TRUNCATED = "OBSERVATION_TRUNCATED"
    PENDING_EVENTS_CANCELLED = "PENDING_EVENTS_CANCELLED"
    CONFIGURATION_WARNING_OBSERVED = "CONFIGURATION_WARNING_OBSERVED"


class DiagnosticClassification(StrEnum):
    SIMULATION_FAILURE = "SIMULATION_FAILURE"
    EXECUTION_LIMIT = "EXECUTION_LIMIT"
    WARNING = "WARNING"
    OBSERVATION = "OBSERVATION"
    INFORMATION = "INFORMATION"


class Direction(StrEnum):
    FORWARD = "FORWARD"
    RETURN = "RETURN"
    LOCAL = "LOCAL"
    DIAGNOSTIC = "DIAGNOSTIC"
    NONE = "NONE"


class EvidenceCompleteness(StrEnum):
    COMPLETE = "COMPLETE"
    PARTIAL = "PARTIAL"
    UNKNOWN = "UNKNOWN"
